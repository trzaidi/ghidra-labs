#!/usr/bin/env python3
"""Assemble the bytecode for challenge 03 (tiny VM).

Image layout:  "TVM1" | u16 code length (little endian) | code bytes

Instruction set (r = register index 0-3):
  0x10 LDI  r, imm8     r = imm8
  0x11 LDC  r, idx      r = input[idx]
  0x20 XOR  r, r2       r ^= r2
  0x21 ADD  r, r2       r += r2
  0x22 ROL  r, n        r = rotate_left_8(r, n)
  0x30 CMP  r, r2       flag = (r == r2)
  0x40 JNE  addr16      if not flag: pc = addr16
  0x41 JMP  addr16      pc = addr16
  0x50 LEN  r           r = strlen(input)
  0xF0 OK               halt, input accepted
  0xFF FAIL             halt, input rejected
"""
import struct
import sys

PASSWORD = "Ph4s3_Sh1ft!"

OPS = {
    "LDI": (0x10, "rb"), "LDC": (0x11, "rb"), "XOR": (0x20, "rr"),
    "ADD": (0x21, "rr"), "ROL": (0x22, "rb"), "CMP": (0x30, "rr"),
    "JNE": (0x40, "a"), "JMP": (0x41, "a"), "LEN": (0x50, "r"),
    "OK": (0xF0, ""), "FAIL": (0xFF, ""),
}


def rol8(v: int, n: int) -> int:
    n &= 7
    return ((v << n) | (v >> (8 - n))) & 0xFF


def key(i: int) -> int:
    return (0xA5 ^ (i * 0x3B)) & 0xFF


def rot(i: int) -> int:
    return (i % 7) + 1


def program():
    """Return a list of (mnemonic, operands) and labels."""
    p = [("LEN", [0]), ("LDI", [1, len(PASSWORD)]), ("CMP", [0, 1]), ("JNE", ["fail"])]
    for i, ch in enumerate(PASSWORD.encode()):
        target = (rol8(ch ^ key(i), rot(i)) + i * 3) & 0xFF
        p += [
            ("LDC", [0, i]),
            ("LDI", [1, key(i)]),
            ("XOR", [0, 1]),
            ("ROL", [0, rot(i)]),
            ("LDI", [2, (i * 3) & 0xFF]),
            ("ADD", [0, 2]),
            ("LDI", [3, target]),
            ("CMP", [0, 3]),
            ("JNE", ["fail"]),
        ]
    p += [("OK", []), ("label", ["fail"]), ("FAIL", [])]
    return p


def size(mn: str) -> int:
    return 1 + {"rb": 2, "rr": 2, "a": 2, "r": 1, "": 0}[OPS[mn][1]]


def assemble() -> bytes:
    prog = program()
    labels, pc = {}, 0
    for mn, ops in prog:
        if mn == "label":
            labels[ops[0]] = pc
        else:
            pc += size(mn)
    out = bytearray()
    for mn, ops in prog:
        if mn == "label":
            continue
        opc, fmt = OPS[mn]
        out.append(opc)
        if fmt == "a":
            out += struct.pack("<H", labels[ops[0]])
        else:
            out += bytes(ops)
    return b"TVM1" + struct.pack("<H", len(out)) + bytes(out)


def main(out_path: str) -> None:
    image = assemble()
    rows = [", ".join(f"0x{b:02x}" for b in image[i:i + 12]) for i in range(0, len(image), 12)]
    with open(out_path, "w") as f:
        f.write("/* Generated by tools/vm_asm.py. Do not edit. */\n")
        f.write("#ifndef VM_CODE_H\n#define VM_CODE_H\n#include <stdint.h>\n")
        f.write(f"static const uint8_t VM_IMAGE[{len(image)}] = {{\n    ")
        f.write(",\n    ".join(rows))
        f.write("\n};\n#endif\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "vm_code.h")
