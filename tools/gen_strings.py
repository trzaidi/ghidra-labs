#!/usr/bin/env python3
"""Generate the encrypted string table for challenge 02.

Each string is XORed with a rolling key: k_i = (key + i * 0x1F) & 0xFF.
The output is a C header with one static array per string. Keys are fixed
so the build is reproducible.
"""
import sys

STEP = 0x1F

STRINGS = [
    ("PROMPT", 0x5A, "Enter access code: "),
    ("PASSWORD", 0xC3, "sp3ctrum-0wl-7"),
    ("GRANTED", 0x17, "Access granted. Flag: "),
    ("FLAG", 0x8E, "GT{x0r_1s_n0t_encrypt10n}"),
    ("DENIED", 0x41, "Access denied."),
]


def encrypt(text: str, key: int) -> bytes:
    return bytes(b ^ ((key + i * STEP) & 0xFF) for i, b in enumerate(text.encode()))


def main(out_path: str) -> None:
    lines = [
        "/* Generated by tools/gen_strings.py. Do not edit. */",
        "#ifndef ENC_STRINGS_H",
        "#define ENC_STRINGS_H",
        "#include <stdint.h>",
        "",
    ]
    for name, key, text in STRINGS:
        blob = encrypt(text, key)
        body = ", ".join(f"0x{b:02x}" for b in blob)
        lines.append(f"#define KEY_{name} 0x{key:02x}")
        lines.append(f"static const uint8_t ENC_{name}[{len(blob)}] = {{ {body} }};")
        lines.append("")
    lines.append("#endif")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "enc_strings.h")
